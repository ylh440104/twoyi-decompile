#!/usr/bin/env bash
# What AOT does the official GSI already ship?
#
# twoyi gets its "second-level boot" because its ROM carries precompiled
# .oat/.vdex/.art. If the GSI already ships them, SiXiang inherits that for free;
# if it does not, we have to run dex2oat ourselves (hours under qemu) -- so
# measure first, decide after.
#
# Mounts /tmp/gsi/system.img (downloaded by make_bundle.sh) and writes
# sixiang/docs/AOT-INVENTORY.md

set -uo pipefail

WORK=/tmp/gsi
OUT=sixiang/docs/AOT-INVENTORY.md
mkdir -p "$(dirname "$OUT")"

if [ ! -f "$WORK/system.img" ]; then
    echo "system.img missing; run sixiang/guest/make_bundle.sh first"
    exit 1
fi

sudo mkdir -p /mnt/gsi
sudo umount /mnt/gsi 2>/dev/null
sudo mount -o loop,ro "$WORK/system.img" /mnt/gsi || { echo "mount failed"; exit 1; }
trap 'sudo umount /mnt/gsi 2>/dev/null' EXIT

count() {   # count dir ext
    local dir=$1 ext=$2
    [ -d "$dir" ] || { echo 0; return; }
    sudo find "$dir" -maxdepth 1 -name "*.$ext" -type f 2>/dev/null | wc -l
}
bytes() {
    local dir=$1 ext=$2
    [ -d "$dir" ] || { echo 0; return; }
    sudo find "$dir" -maxdepth 1 -name "*.$ext" -type f -printf '%s\n' 2>/dev/null \
        | awk '{s+=$1} END{print s+0}'
}

FW=/mnt/gsi/system/framework
FW64=$FW/oat/arm64
echo "== framework AOT =="
sudo ls "$FW64" 2>/dev/null | head -20 | sed 's/^/  /'

OAT=$(count "$FW64" oat);    VDEX=$(count "$FW64" vdex); ART=$(count "$FW64" art)
OAT_B=$(bytes "$FW64" oat);  VDEX_B=$(bytes "$FW64" vdex); ART_B=$(bytes "$FW64" art)

echo "  framework oat=$OAT vdex=$VDEX art=$ART"

APPS=0; APPS_B=0
if [ -d /mnt/gsi/system/app ]; then
    APPS=$(sudo find /mnt/gsi/system/app -type f -path '*/oat/arm64/*.vdex' 2>/dev/null | wc -l)
    APPS_B=$(sudo find /mnt/gsi/system/app -type f -path '*/oat/arm64/*' -printf '%s\n' 2>/dev/null \
             | awk '{s+=$1} END{print s+0}')
fi
PRIV=0
if [ -d /mnt/gsi/system/priv-app ]; then
    PRIV=$(sudo find /mnt/gsi/system/priv-app -type f -path '*/oat/arm64/*.vdex' 2>/dev/null | wc -l)
fi

echo "  app vdex=$APPS  priv-app vdex=$PRIV"

{
    echo "# AOT inventory of the Android 17 GSI"
    echo
    echo "> generated by \`sixiang/aot/inventory.sh\` in GitHub Actions"
    echo "> run: $GITHUB_RUN_ID  commit: $GITHUB_SHA"
    echo
    echo "The question: does the official GSI already ship precompiled code, or"
    echo "would SiXiang have to run dex2oat at first boot?"
    echo
    echo "| location | .oat | .vdex | .art | bytes |"
    echo "|---|---|---|---|---|"
    echo "| system/framework/oat/arm64 | $OAT | $VDEX | $ART | $((OAT_B + VDEX_B + ART_B)) |"
    echo "| system/app/*/oat/arm64 (vdex) | — | $APPS | — | $APPS_B |"
    echo "| system/priv-app/*/oat/arm64 (vdex) | — | $PRIV | — | — |"
    echo
    if [ "$OAT" -gt 0 ] || [ "$VDEX" -gt 0 ]; then
        echo "**Verdict: the GSI ships AOT artifacts.** No dex2oat needed for the"
        echo "framework; boot should not stall on compilation."
    else
        echo "**Verdict: no framework AOT in the image.** SiXiang must precompile"
        echo "(boot.art via dex2oat) or the first boot will spend minutes in dex2oat."
    fi
} > "$OUT"

cat "$OUT"
echo "DONE"